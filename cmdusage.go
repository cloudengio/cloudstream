// Usage of cloudstream
//
//	cloudstream is tool for concurrent and resumable downloads from web or cloud
//	services. It aims to be the fastest and most reliable tool for downloading large
//	files or files from unreliable, slow or rate-limited services.
//
//	       cache - Download files from various services with local caching and resumption support. Downloads rely on byte range requests and are designed to be as fast as possible. Support for rate control is also provided.
//	      stream - Stream files from various services that do not require authentication. The files may be processed as they are downloaded, allowing for real-time processing of the data.
//	google-drive - Download files from Google Drive.
//	      digest - Compute/compared the hash digests of files.
